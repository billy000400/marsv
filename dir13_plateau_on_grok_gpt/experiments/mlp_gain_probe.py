"""MLP-gain intervention: is the plateau sharpness BUILT by the early blocks' MLPs?

The readout-rebalancing probe (rebalance_probe.py) showed no readout-level bias can move w or t*
at all -- d(t) is invariant to an additive logit bias. So the sharpness must be produced upstream.
The depth control in Experiment 5 localised it: w = 0.344 / 0.763 / 0.806 / 0.806 when the
interpolation is injected at blocks 0 / 4 / 8 / 11, i.e. essentially all of it is generated by
blocks 1-4. That is an observation, not an intervention.

Here we intervene. We scale the MLP-branch output of blocks 1-4 by a gain g (leaving attention,
LayerNorm and every other block untouched) and re-run the frozen assay:

    Block.forward(x) = x + attn(ln_1 x) + g * mlp(ln_2 x)      for the targeted blocks only.

g = 1 is the unmodified model. g < 1 removes MLP contribution, g > 1 amplifies it. Endpoints are
recomputed under each modified model, so d(t) always measures the *modified* model's own path
between its own endpoints -- the assay itself is unchanged.

Specificity control: the same gains applied to blocks 8-11 instead, which the depth measurement
says contribute almost nothing to the sharpness. If sharpness is really made in blocks 1-4, the
early intervention should move w and the late one should not.

Subsample: N_PAIRS random pairs of the 2080, fixed seed, block-0 interpolation, step-30000 fresh
character checkpoint -- the same setting as Experiment 5, so widths are directly comparable.

Raw -> results/mlp_gain_raw.npz, stats -> results/mlp_gain_summary.json.
"""
import os, sys, json, time, itertools
import numpy as np
import torch

sys.path.insert(0, os.path.dirname(__file__))
from matthew_assay import run_pair, is_plateau, pava_isotonic, iso_crossing, self_test
from allpairs_sweep import load_vocab, load_model, CONTEXT, N_T, FINAL_STEP

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
BLOCK = 0
N_PAIRS = 150
SEED = 0
EARLY = [1, 2, 3, 4]
LATE = [8, 9, 10, 11]
GAINS = [0.0, 0.5, 1.5]


class ScaledMLP(torch.nn.Module):
    """Wraps a block's MLP so its output (the residual-branch contribution) is scaled by `gain`."""

    def __init__(self, mlp, gain):
        super().__init__()
        self.mlp = mlp
        self.gain = gain

    def forward(self, x):
        return self.gain * self.mlp(x)


def set_gain(model, blocks, gain, saved):
    """Install/restore the gain on the given blocks. `saved` holds the original MLP modules."""
    for l in blocks:
        if l not in saved:
            saved[l] = model.blocks[l].mlp
        model.blocks[l].mlp = ScaledMLP(saved[l], gain)


def restore(model, saved):
    for l, m in saved.items():
        model.blocks[l].mlp = m
    saved.clear()


def sweep(model, seqs, pairs, ts, device):
    """Run the assay for every pair under the currently installed gain. Returns per-pair arrays."""
    w, tstar, strict, dev = [], [], [], []
    for ia, ib in pairs:
        r = run_pair(model, seqs[ia], seqs[ib], BLOCK, ts, device)
        ok, wi, t_lo, t_hi, mdev = is_plateau(ts, r["d_logit"])
        w.append(wi)
        tstar.append(iso_crossing(ts, pava_isotonic(r["d_logit"]), 0.5))
        strict.append(bool(ok))
        dev.append(mdev)
    return (np.array(w, dtype=float), np.array(tstar, dtype=float),
            np.array(strict, dtype=bool), np.array(dev, dtype=float))


def main():
    torch.cuda.set_per_process_memory_fraction(0.225)
    torch.set_num_threads(2)
    device = "cuda"
    self_test()

    stoi = load_vocab()
    chars = sorted(stoi, key=lambda c: stoi[c])
    V = len(chars)
    ts = np.linspace(0.0, 1.0, N_T)
    seqs = [np.array([stoi[c] for c in CONTEXT + ch], dtype=np.int64) for ch in chars]
    all_pairs = list(itertools.combinations(range(V), 2))
    rng = np.random.default_rng(SEED)
    pairs = [all_pairs[i] for i in rng.choice(len(all_pairs), N_PAIRS, replace=False)]

    model = load_model(FINAL_STEP, device)
    saved = {}
    t0 = time.time()

    conds = [("baseline", [], 1.0)]
    conds += [(f"early_g{g}", EARLY, g) for g in GAINS]
    conds += [(f"late_g{g}", LATE, g) for g in GAINS]

    out, raw = {}, {}
    for name, blocks, g in conds:
        restore(model, saved)
        if blocks:
            set_gain(model, blocks, g, saved)
        w, tstar, strict, dev = sweep(model, seqs, pairs, ts, device)
        out[name] = {"blocks": blocks, "gain": g,
                     "median_w": round(float(np.nanmedian(w)), 4),
                     "mean_w": round(float(np.nanmean(w)), 4),
                     "iqr_w": [round(float(np.nanpercentile(w, 25)), 4),
                               round(float(np.nanpercentile(w, 75)), 4)],
                     "strict_frac": round(float(strict.mean()), 4),
                     "median_max_iso_dev": round(float(np.nanmedian(dev)), 4),
                     "median_t_star": round(float(np.nanmedian(tstar)), 4)}
        raw[name + "_w"] = w
        raw[name + "_tstar"] = tstar
        print(f"{name:12s} median_w={out[name]['median_w']:.4f} "
              f"strict={out[name]['strict_frac']:.3f} ({time.time()-t0:.0f}s)", flush=True)
    restore(model, saved)

    # Paired shifts against the unmodified model (same pairs, so pair them).
    base_w = raw["baseline_w"]
    base_t = raw["baseline_tstar"]
    for name in out:
        if name == "baseline":
            continue
        dw = raw[name + "_w"] - base_w
        dt = raw[name + "_tstar"] - base_t
        out[name]["median_paired_dw"] = round(float(np.nanmedian(dw)), 4)
        out[name]["frac_w_increased"] = round(float(np.nanmean(dw > 0)), 4)
        out[name]["median_abs_paired_dtstar"] = round(float(np.nanmedian(np.abs(dt))), 4)

    summary = {"context": CONTEXT, "step": FINAL_STEP, "block": BLOCK, "n_t": N_T,
               "n_pairs": N_PAIRS, "seed": SEED, "early_blocks": EARLY, "late_blocks": LATE,
               "gains": GAINS, "conditions": out}
    print(json.dumps(summary, indent=2), flush=True)
    with open(os.path.join(RES, "mlp_gain_summary.json"), "w") as f:
        json.dump({"summary": summary,
                   "pairs": [[chars[a], chars[b]] for a, b in pairs]}, f, indent=1)
    np.savez_compressed(os.path.join(RES, "mlp_gain_raw.npz"), ts=ts, **raw)
    print(f"DONE in {time.time()-t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
